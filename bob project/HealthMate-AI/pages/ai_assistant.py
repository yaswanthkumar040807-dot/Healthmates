"""
HealthMate AI — AI Wellness Assistant Page
"""
import streamlit as st

import database as db
from services.assistant_service import (
    llm_response, rule_based_response, SUGGESTED_QUESTIONS,
    MEDICAL_DISCLAIMER, EMERGENCY_RESPONSE,
)
from config import AI_AVAILABLE


def _source_badge(source: str) -> str:
    if source == "openai":
        return "<span class='hm-tag' style='background:#dbeafe;color:#1d4ed8;'>🤖 AI-powered</span>"
    return "<span class='hm-tag' style='background:#d4edda;color:#1a6b4a;'>🌿 Rule-based</span>"


def render():
    st.markdown("# 🤖 AI Wellness Assistant")
    st.markdown(
        "<p class='hm-muted'>Ask general wellness questions about sleep, nutrition, "
        "physical activity, stress, hydration, or healthy habits.</p>",
        unsafe_allow_html=True,
    )

    # AI status banner
    if AI_AVAILABLE:
        st.success("✅ AI provider configured. Responses are generated by the configured language model.")
    else:
        st.info(
            "🌿 **Rule-based mode active.** "
            "Set `OPENAI_API_KEY` in your `.env` file to enable AI-powered responses. "
            "The built-in assistant provides evidence-informed wellness guidance without an API key."
        )

    # Safety disclaimer
    st.warning(
        "⚠️ **Important:** HealthMate AI provides general wellness education only. "
        "It does **not** diagnose illnesses, prescribe medication, or replace professional "
        "medical advice. For emergencies, contact your local emergency services immediately."
    )

    st.markdown("---")

    # ── Suggested questions ────────────────────────────────────────────────────
    st.markdown("#### 💡 Suggested Questions")
    cols = st.columns(2)
    for i, q in enumerate(SUGGESTED_QUESTIONS[:8]):
        if cols[i % 2].button(q, key=f"sq_{i}", use_container_width=True):
            st.session_state["assistant_input"] = q

    st.markdown("---")

    # ── Chat interface ────────────────────────────────────────────────────────
    if "chat_messages" not in st.session_state:
        st.session_state.chat_messages = []

    # Display conversation
    for msg in st.session_state.chat_messages:
        role = msg["role"]
        with st.chat_message(role):
            st.markdown(msg["content"], unsafe_allow_html=True)
            if role == "assistant":
                st.markdown(_source_badge(msg.get("source", "fallback")), unsafe_allow_html=True)

    # Input
    prefill = st.session_state.pop("assistant_input", "")
    user_input = st.chat_input("Ask a wellness question…")

    # Also handle suggested-question pre-fill
    if prefill and not user_input:
        user_input = prefill

    if user_input:
        user_input = user_input.strip()
        if not user_input:
            return

        # Append user message
        st.session_state.chat_messages.append({"role": "user", "content": user_input})
        with st.chat_message("user"):
            st.markdown(user_input)

        # Build history for LLM context
        history = [{"role": m["role"], "content": m["content"]}
                   for m in st.session_state.chat_messages[:-1]]

        with st.spinner("Thinking…"):
            response, source = llm_response(user_input, history)

        # Append assistant response
        st.session_state.chat_messages.append({
            "role": "assistant",
            "content": response,
            "source": source,
        })

        # Persist to DB if logged in
        uid = st.session_state.get("user_id")
        if uid:
            db.add_chat_message(uid, "user", user_input, "user")
            db.add_chat_message(uid, "assistant", response, source)

        with st.chat_message("assistant"):
            st.markdown(response, unsafe_allow_html=True)
            st.markdown(_source_badge(source), unsafe_allow_html=True)

    # Clear conversation
    if st.session_state.chat_messages:
        st.markdown("---")
        col1, col2 = st.columns([1, 4])
        with col1:
            if st.button("🗑️ Clear conversation"):
                st.session_state.chat_messages = []
                uid = st.session_state.get("user_id")
                if uid:
                    db.clear_chat_history(uid)
                st.rerun()
